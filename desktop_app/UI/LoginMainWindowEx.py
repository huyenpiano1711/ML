"""
LoginMainWindowEx.py - Sign in / Create account window.

    LoginMainWindow.ui    -> designed in Qt Designer
    LoginMainWindow.py    -> generated by pyuic6 (do NOT edit by hand)
    LoginMainWindowEx.py  -> this file: signals & slots

Regenerate after editing the .ui:
    pyuic6 desktop_app/UI/LoginMainWindow.ui -o desktop_app/UI/LoginMainWindow.py
"""
import json
import sys
from pathlib import Path

from PyQt6.QtCore import QSettings, Qt
from PyQt6.QtWidgets import QApplication, QMainWindow, QLineEdit, QMessageBox

from desktop_app.UI.LoginMainWindow import Ui_MainWindow
from desktop_app.dal.user_dao import (UserDao, AUTH_EMPTY, AUTH_OK, MAX_EMAIL_LENGTH, MAX_FAILED_LOGINS,
                                      MAX_NAME_LENGTH, MAX_PASSWORD_LENGTH, MAX_USERNAME_LENGTH)
from desktop_app.utils.UIUtil import UIUtil, ImageBackground

PAGE_LOGIN, PAGE_REGISTER = 0, 1
PROJECT_DIR = Path(__file__).resolve().parents[2]


class LoginMainWindowEx(Ui_MainWindow):
    def __init__(self):
        self.settings = QSettings("AutoWise", "AutoWiseAI")
        self.mainUi = None
        self.failedThisRun = 0         # wrong sign-ins in a row in this run: 3 -> the app closes (course exam rule)

    def setupUi(self, MainWindow):
        super().setupUi(MainWindow)
        self.MainWindow = MainWindow
        UIUtil.setupWindow(MainWindow)
        image = UIUtil.firstImage("login.jpg", "login.png", "bg_login.jpg")
        self.loginBackground = ImageBackground(self.frameLoginVisual, image, shade=(120, 60, 30))
        self.labelLoginMessage.hide()
        self.labelRegisterMessage.hide()
        UserDao.ensureDefaultAdmin()
        self.showLiveStats()
        self.setupInputLimits()
        self.loadSavedUser()
        self.setupSignalAndSlot()
        self.showPage(PAGE_LOGIN)

    def showWindow(self):
        self.MainWindow.show()

    def setupSignalAndSlot(self):
        self.pushButtonLogin.clicked.connect(self.processLogin)
        self.lineEditUserName.returnPressed.connect(self.lineEditPassword.setFocus)
        self.lineEditPassword.returnPressed.connect(self.processLogin)
        self.checkBoxShowPassword.toggled.connect(self.togglePassword)
        self.pushButtonShowRegister.clicked.connect(lambda: self.showPage(PAGE_REGISTER))
        self.pushButtonShowLogin.clicked.connect(lambda: self.showPage(PAGE_LOGIN))
        self.pushButtonRegister.clicked.connect(self.processRegister)
        self.lineEditConfirmPassword.returnPressed.connect(self.processRegister)
        self.pushButtonExit.clicked.connect(self.MainWindow.close)

    # ------------------------------------------------------------------ helpers
    def setupInputLimits(self):
        """Maximum lengths, and messages shown as plain text (a name like <h1>..</h1> is not HTML)."""
        limits = {self.lineEditUserName: MAX_USERNAME_LENGTH, self.lineEditPassword: MAX_PASSWORD_LENGTH,
                  self.lineEditFullName: MAX_NAME_LENGTH, self.lineEditRegisterUserName: MAX_USERNAME_LENGTH,
                  self.lineEditEmail: MAX_EMAIL_LENGTH, self.lineEditRegisterPassword: MAX_PASSWORD_LENGTH,
                  self.lineEditConfirmPassword: MAX_PASSWORD_LENGTH}
        for box, limit in limits.items():
            box.setMaxLength(limit)
        for label in (self.labelLoginMessage, self.labelRegisterMessage):
            label.setTextFormat(Qt.TextFormat.PlainText)

    def showLiveStats(self):
        """The 3 numbers on the picture panel come from the trained model files, not typed in the .ui."""
        model_dir = PROJECT_DIR / "models" / "price_prediction"
        try:
            metrics = json.loads((model_dir / "metrics.json").read_text(encoding="utf-8"))
            app = metrics.get("test_metrics_app_path") or metrics.get("test_metrics", {})
            self.labelStatAccuracyValue.setText(f"R² {app['r2_usd']:.2f}")
            self.labelStatAccuracy.setText("PRICE MODEL FIT (TEST)")
        except Exception:                                   # noqa: BLE001 - keep the designed text
            pass
        try:
            meta = json.loads((model_dir / "model_metadata.json").read_text(encoding="utf-8"))
            rows = meta["train_size"] + meta["val_size"] + meta["test_size"]
            self.labelStatListingsValue.setText(f"{rows / 1000:.0f}K")
            schema = json.loads((PROJECT_DIR / "src" / "features" / "feature_schema.json").read_text(encoding="utf-8"))
            makes = next(f for f in schema["features"] if f["name"] == "manufacturer")
            self.labelStatBrandsValue.setText(str(len(makes["ui_options"])))
        except Exception:                                   # noqa: BLE001
            pass

    def showPage(self, page):
        self.stackedWidgetAuth.setCurrentIndex(page)
        self.labelLoginMessage.hide()
        self.labelRegisterMessage.hide()
        if page == PAGE_LOGIN:
            (self.lineEditPassword if self.lineEditUserName.text() else self.lineEditUserName).setFocus()
        else:
            self.lineEditFullName.setFocus()

    def showMessage(self, label, text, success=False):
        label.setProperty("role", "success" if success else "error")
        UIUtil.repolish(label)
        label.setText(text)
        label.show()

    def togglePassword(self, show):
        mode = QLineEdit.EchoMode.Normal if show else QLineEdit.EchoMode.Password
        self.lineEditPassword.setEchoMode(mode)

    def loadSavedUser(self):
        saved = self.settings.value("savedUserName", "")
        if saved:
            self.lineEditUserName.setText(saved)
            self.checkBoxSave.setChecked(True)

    # ------------------------------------------------------------------ sign in
    def processLogin(self):
        """Sign in. Wrong password: message with the attempts left; 3 wrong in a row on an account locks it for
        5 minutes (database). 3 failed sign-ins in a row in this run close the application."""
        uid = self.lineEditUserName.text().strip()
        pwd = self.lineEditPassword.text()
        result = UserDao.authenticate(uid, pwd)
        if result.status == AUTH_EMPTY:
            self.showMessage(self.labelLoginMessage, result.message)
            return
        if result.status != AUTH_OK:
            self.failedThisRun += 1
            if self.failedThisRun >= MAX_FAILED_LOGINS:
                QMessageBox.critical(self.MainWindow, "Sign-in failed",
                                     f"{result.message}\n\nYou failed to sign in {MAX_FAILED_LOGINS} times in a row. "
                                     "AutoWise will close now.")
                QApplication.quit()
                sys.exit(0)
            self.showMessage(self.labelLoginMessage, result.message)
            self.lineEditPassword.selectAll()
            self.lineEditPassword.setFocus()
            return
        self.failedThisRun = 0
        us = result.user
        self.settings.setValue("savedUserName", us.username if self.checkBoxSave.isChecked() else "")
        self.openMainWindow(us)

    # ------------------------------------------------------------------ create account
    def processRegister(self):
        full_name = self.lineEditFullName.text()
        username = self.lineEditRegisterUserName.text()
        email = self.lineEditEmail.text()
        pwd = self.lineEditRegisterPassword.text()
        confirm = self.lineEditConfirmPassword.text()
        errors = UserDao.validateRegister(full_name, username, email, pwd, confirm)
        if not errors and not self.checkBoxAgree.isChecked():
            errors.append("Please tick the box to confirm.")
        if errors:
            self.showMessage(self.labelRegisterMessage, "\n".join(errors))
            return
        us = UserDao.register(full_name, username, email, pwd)
        if us is None:
            self.showMessage(self.labelRegisterMessage, "Could not create the account. Please try again.")
            return
        for box in (self.lineEditFullName, self.lineEditRegisterUserName, self.lineEditEmail,
                    self.lineEditRegisterPassword, self.lineEditConfirmPassword):
            box.clear()
        self.checkBoxAgree.setChecked(False)
        self.lineEditUserName.setText(us.username)
        self.lineEditPassword.clear()
        self.showPage(PAGE_LOGIN)
        self.showMessage(self.labelLoginMessage, f"Account created. Welcome, {us.full_name}! Please sign in.",
                         success=True)

    # ------------------------------------------------------------------ navigation
    def openMainWindow(self, us):
        """Admin -> admin panel, user -> the car advisor. Any error is shown instead of closing the app."""
        try:
            if us.is_admin:
                from desktop_app.UI.AdminMainWindowEx import AdminMainWindowEx
                self.mainUi = AdminMainWindowEx(us, self)
            else:
                from desktop_app.UI.AutoWiseMainWindowEx import AutoWiseMainWindowEx
                self.mainUi = AutoWiseMainWindowEx(us, self)
            self.mainUi.setupUi(QMainWindow())
            self.mainUi.showWindow()
        except Exception as exc:                            # noqa: BLE001
            import traceback
            traceback.print_exc()
            QMessageBox.critical(self.MainWindow, "Could not open AutoWise", f"{type(exc).__name__}: {exc}")
            self.mainUi = None
            return
        self.lineEditPassword.clear()
        self.labelLoginMessage.hide()
        self.MainWindow.hide()

    def backFromMainWindow(self):
        """Called by AutoWiseMainWindowEx when the user signs out."""
        self.mainUi = None
        self.showPage(PAGE_LOGIN)
        self.showWindow()
