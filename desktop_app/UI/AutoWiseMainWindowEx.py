"""
AutoWiseMainWindowEx.py - AutoWise has exactly 3 screens (project overview, section 5):
    (before)  LoginMainWindow - sign in / create account (account saved in SQLite)
    Screen 1  pageWelcome  - user info, pre-filled from the signed-in account
    Screen 2  pageVehicle  - vehicle details + budget
    Screen 3  pageResults  - predicted price, Top 5 matches, other cars in the same price range

    AutoWiseMainWindow.ui    -> designed in Qt Designer
    AutoWiseMainWindow.py    -> generated by pyuic6 (do NOT edit by hand)
    AutoWiseMainWindowEx.py  -> this file: signals & slots

Regenerate after editing the .ui:
    pyuic6 desktop_app/UI/AutoWiseMainWindow.ui -o desktop_app/UI/AutoWiseMainWindow.py
"""
import sys
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parents[2]          # D:\AutoWise
if str(PROJECT_DIR) not in sys.path:
    sys.path.insert(0, str(PROJECT_DIR))

from PyQt6.QtCore import Qt, QEventLoop, QLocale
from PyQt6.QtWidgets import QApplication, QMessageBox

from desktop_app.UI.AutoWiseMainWindow import Ui_MainWindow
from desktop_app.utils.UIUtil import UIUtil, ImageBackground
from desktop_app.controllers import PAGE_WELCOME, PAGE_VEHICLE
from desktop_app.controllers.results_controller import ResultsController
from desktop_app.controllers.user_controller import UserController
from desktop_app.controllers.vehicle_controller import VehicleController, FIELD_NAMES
from desktop_app.widgets.vehicle_card import labelOf, money
from backend.schemas.vehicle_input import FEATURES


class AutoWiseMainWindowEx(Ui_MainWindow):
    def __init__(self, user=None, loginUi=None):
        self.user = user                      # signed-in User (from LoginMainWindowEx); None = guest
        self.loginUi = loginUi

    def setupUi(self, MainWindow):
        super().setupUi(MainWindow)
        self.MainWindow = MainWindow
        self.userController = UserController(self)
        self.vehicleController = VehicleController(self)
        self.resultsController = ResultsController(self)
        UIUtil.setupWindow(MainWindow)
        image = UIUtil.firstImage("hero.jpg", "hero.png", "bg_hero.jpg")
        self.heroBackground = ImageBackground(self.frameHero, image)
        self.widgetAdvancedFields.setVisible(False)
        self.labelTopEmpty.hide()
        self.labelSimilarEmpty.hide()
        self.pushButtonLogout.setVisible(self.loginUi is not None)
        self.setupSpinBoxes()
        self.loadOptions()
        if self.user is not None:
            self.lineEditFullName.setText(self.user.full_name or "")
            self.labelHeaderUser.setText(f"Signed in as {self.user.full_name or self.user.username}")
        self.setupSignalAndSlot()
        self.updateSummary()
        self.goToPage(PAGE_WELCOME)

    def showWindow(self):
        self.MainWindow.show()
        self.resultsController.warmUp()

    # ------------------------------------------------------------------ setup
    def setupSignalAndSlot(self):
        self.pushButtonStart.clicked.connect(self.userController.start)
        self.lineEditFullName.returnPressed.connect(self.userController.start)
        self.lineEditDisplayName.returnPressed.connect(self.userController.start)
        self.pushButtonBackWelcome.clicked.connect(self.vehicleController.goBack)
        self.pushButtonAnalyze.clicked.connect(self.analyzeVehicle)
        self.pushButtonBackVehicle.clicked.connect(lambda: self.goToPage(PAGE_VEHICLE))
        self.pushButtonReset.clicked.connect(self.vehicleController.reset)
        self.pushButtonToggleAdvanced.clicked.connect(self.toggleAdvanced)
        self.pushButtonLogout.clicked.connect(self.processLogout)
        self.comboBoxManufacturer.currentIndexChanged.connect(self.vehicleController.refreshModels)
        self.spinBoxBudget.valueChanged.connect(self.horizontalSliderBudget.setValue)
        self.horizontalSliderBudget.valueChanged.connect(self.spinBoxBudget.setValue)
        for combo in self.requiredCombos().values():
            combo.currentIndexChanged.connect(self.updateSummary)
        for box in (self.spinBoxYear, self.spinBoxOdometer, self.spinBoxBudget):
            box.valueChanged.connect(self.updateSummary)

    def setupSpinBoxes(self):
        english = QLocale(QLocale.Language.English, QLocale.Country.UnitedStates)
        for box in (self.spinBoxYear, self.spinBoxOdometer, self.spinBoxBudget):
            box.setLocale(english)                       # 90,000
            box.lineEdit().setTextMargins(10, 0, 0, 0)

    def userName(self):
        return self.userController.userName()

    def requiredCombos(self):
        return {"manufacturer": self.comboBoxManufacturer, "model_base": self.comboBoxModel,
                "type": self.comboBoxType, "condition": self.comboBoxCondition,
                "fuel": self.comboBoxFuel, "transmission": self.comboBoxTransmission}

    def optionalCombos(self):
        return {"drive": self.comboBoxDrive, "cylinders": self.comboBoxCylinders,
                "paint_color": self.comboBoxPaintColor, "title_status": self.comboBoxTitleStatus,
                "state": self.comboBoxState}

    def loadOptions(self):
        """Options come from src/features/feature_schema.json (same source as the model)."""
        for name, combo in self.requiredCombos().items():
            if name == "model_base":
                continue
            combo.clear()
            combo.addItem(f"Select {FIELD_NAMES[name].lower()}…", None)
            for value in FEATURES[name].get("ui_options", []):
                combo.addItem(labelOf(name, value), value)
        for name, combo in self.optionalCombos().items():
            combo.clear()
            combo.addItem("Any", None)
            for value in FEATURES[name].get("ui_options", []):
                combo.addItem(labelOf(name, value), value)
        self.comboBoxManufacturer.setMaxVisibleItems(14)
        self.comboBoxState.setMaxVisibleItems(14)
        self.vehicleController.refreshModels()

    # ------------------------------------------------------------------ navigation
    def goToPage(self, index):
        self.stackedWidgetMain.setCurrentIndex(index)
        for i, step in enumerate((self.labelStep1, self.labelStep2, self.labelStep3)):
            step.setProperty("active", i == index)
            step.setProperty("done", i < index)
            UIUtil.repolish(step)

    def toggleAdvanced(self):
        show = not self.widgetAdvancedFields.isVisible()
        self.widgetAdvancedFields.setVisible(show)
        self.pushButtonToggleAdvanced.setText(f"{'−' if show else '+'}  ADVANCED OPTIONS (OPTIONAL)")

    def processLogout(self):
        if self.loginUi is not None:
            self.loginUi.backFromMainWindow()
        self.MainWindow.close()

    # ------------------------------------------------------------------ form
    def updateSummary(self):
        make = self.comboBoxManufacturer.currentData()
        model = self.comboBoxModel.currentData()
        if make is None:
            self.labelSummaryTitle.setText("No car selected")
            self.labelSummaryDetail.setText("Pick a make and model to get started.")
            return
        title = f"{self.comboBoxManufacturer.currentText()} {self.comboBoxModel.currentText() if model else ''}"
        self.labelSummaryTitle.setText(f"{title.strip()} · {self.spinBoxYear.value()}")
        parts = [f"{self.spinBoxOdometer.value():,} mi"]
        for name in ("type", "condition", "fuel", "transmission"):
            if self.requiredCombos()[name].currentData():
                parts.append(self.requiredCombos()[name].currentText())
        self.labelSummaryDetail.setText(" · ".join(parts) + f"\nBudget: {money(self.spinBoxBudget.value())}")

    # ------------------------------------------------------------------ analysis
    def analyzeVehicle(self):
        vehicle = self.vehicleController.validatedInput()
        if vehicle is None:
            return
        QApplication.setOverrideCursor(Qt.CursorShape.WaitCursor)
        self.pushButtonAnalyze.setEnabled(False)
        self.pushButtonAnalyze.setText("ANALYZING…")
        QApplication.processEvents()
        try:
            result = self.resultsController.analyze(vehicle)
        finally:
            self.pushButtonAnalyze.setEnabled(True)
            self.pushButtonAnalyze.setText("ANALYZE && FIND CARS  ")
            QApplication.restoreOverrideCursor()
        self.resultsController.show(vehicle, result)

    # ------------------------------------------------------------------ utils
    def repolish(self, widget):
        UIUtil.repolish(widget)

    def settleLayout(self):
        """Apply pending layouts; clicks stay queued, so ANALYZE cannot start again from here."""
        QApplication.processEvents(QEventLoop.ProcessEventsFlag.ExcludeUserInputEvents)

    def showWarning(self, title, text):
        box = QMessageBox(self.MainWindow)
        box.setIcon(QMessageBox.Icon.Warning)
        box.setWindowTitle(title)
        box.setText(text)
        box.exec()
