    def loadOptions(self):
        """Options come from src/features/feature_schema.json (same source as the model)."""
        for name, combo in self.requiredCombos().items():
            if name == "model_base":
                continue
            combo.clear()
            combo.addItem("Type or pick a make…" if name == "manufacturer" else NOT_SURE, None)
            for value in FEATURES[name].get("ui_options", []):
                combo.addItem(labelOf(name, value), value)
        for name, combo in self.optionalCombos().items():
            combo.clear()
            combo.addItem(NOT_SURE, None)              # same first choice as the other optional fields
            for value in FEATURES[name].get("ui_options", []):
                combo.addItem(labelOf(name, value), value)
        self.comboBoxManufacturer.setMaxVisibleItems(14)
        self.comboBoxState.setMaxVisibleItems(14)
        for combo in (self.comboBoxManufacturer, self.comboBoxModel):
            self.makeSearchable(combo)
        self.vehicleController.refreshModels()

    def makeSearchable(self, combo):
        """Make and model: type part of the name (suggestions appear) or scroll the list and pick."""
        combo.setEditable(True)
        combo.lineEdit().setFont(combo.font())          # the new line edit misses the window font (Inter 13px)
        combo.setInsertPolicy(QComboBox.InsertPolicy.NoInsert)
        completer = combo.completer()
        completer.setCompletionMode(QCompleter.CompletionMode.PopupCompletion)
        completer.setFilterMode(Qt.MatchFlag.MatchContains)
        completer.setCaseSensitivity(Qt.CaseSensitivity.CaseInsensitive)
        completer.popup().setStyleSheet(SUGGESTION_STYLE)       # the list under the box while typing
        # the filled-in end of a name ("Cam" + "ry") looks like a grey suggestion, not a red selection
        combo.setStyleSheet("QComboBox { selection-background-color: #EEEEF1; selection-color: #A1A1AA; }")
        palette = combo.lineEdit().palette()                     # after setStyleSheet, which resets the palette
        palette.setColor(QPalette.ColorRole.PlaceholderText, QColor(HINT_COLOR))
        combo.lineEdit().setPalette(palette)
        combo.lineEdit().textChanged.connect(lambda text: self.dropHintText(combo, text))
        combo.lineEdit().textEdited.connect(lambda text: self.completeTypedText(combo, text))
        combo.lineEdit().editingFinished.connect(lambda: self.matchTypedText(combo))
        combo.currentIndexChanged.connect(lambda index: self.showHint(combo, index))
        self.showHint(combo, combo.currentIndex())

    @staticmethod
    def showHint(combo, index):
        """Item 0 ("Type or pick…", no value) is shown as a grey hint, not as text to delete."""
        if index <= 0 and combo.lineEdit() is not None:
            combo.lineEdit().setPlaceholderText(combo.itemText(0))
            if not combo.lineEdit().property("typing"):          # keep what the user is typing
                combo.lineEdit().clear()

    @staticmethod
    def dropHintText(combo, text):
        """Qt writes the text of item 0 into the box in some cases (Enter on a name that is not in the list,
        reset). The hint must stay a grey placeholder, never text to delete, so it is taken out again."""
        hint = combo.itemText(0)
        if combo.currentIndex() <= 0 and hint and text.startswith(hint):
            combo.lineEdit().setText(text[len(hint):])

    @staticmethod
    def completeTypedText(combo, text):
        """While typing, the first name that starts with the typed letters is chosen at once: "Cam" shows
        "Camry" ("ry" in grey) and the summary already says Camry. Typing on replaces the grey part;
        Backspace deletes normally. Letters that start no name leave nothing chosen."""
        box = combo.lineEdit()
        typed = len(text)
        growing = typed > (box.property("typedLength") or 0)
        box.setProperty("typedLength", typed)
        lowered = text.strip().lower()
        match = next((i for i in range(1, combo.count()) if lowered and combo.itemText(i).lower().startswith(lowered)), 0)
        box.setProperty("typing", True)
        if combo.currentIndex() != match:
            combo.setCurrentIndex(match)                          # summary, model list, constraints follow
        box.setProperty("typing", False)
        label = combo.itemText(match) if match else text
        if match and growing:
            box.setText(label)
            box.setSelection(typed, len(label) - typed)
        else:
            box.setText(text)                                     # Backspace / no match: exactly what was typed

    @staticmethod
    def matchTypedText(combo):
        """Typed text -> the list item it names (any letter case; one unique partial match is enough).
        Text that names no item selects nothing, so the form asks for the make / model."""
        text = combo.currentText().strip().lower()
        if not text:
            combo.setCurrentIndex(0)
            return
        items = [(i, combo.itemText(i).lower(), str(combo.itemData(i) or "").lower()) for i in range(1, combo.count())]
        exact = [i for i, label, value in items if text in (label, value)]
        partial = [i for i, label, value in items if text in label or text in value]
        current = combo.currentIndex()
        if not exact and current > 0 and combo.itemText(current).lower().startswith(text):
            match = [current]                                      # chosen while typing ("Cam" -> Camry)
        else:
            match = exact or (partial if len(partial) == 1 else [])
        combo.setCurrentIndex(match[0] if match else 0)
        if match:
            combo.lineEdit().setText(combo.itemText(match[0]))       # the full name, also when the index stayed

