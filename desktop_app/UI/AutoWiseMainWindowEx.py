    def makeCardsEqualWidth(self):
        """The 5 Top cards (and the 3 columns of same-price cards) share the width equally, whatever the
        photo or text inside: the photo labels ignore their picture's width and every card gets stretch 1."""
        from PyQt6.QtWidgets import QSizePolicy
        cards = self.resultsController.topCards + self.resultsController.similarCards
        for card in cards:
            policy = card.labelImage.sizePolicy()
            policy.setHorizontalPolicy(QSizePolicy.Policy.Ignored)
            card.labelImage.setSizePolicy(policy)
        row = self.horizontalLayoutTopMatches
        for card in self.resultsController.topCards:
            row.setStretch(row.indexOf(card.frame), 1)
        for column in range(self.gridLayoutSimilarPrice.columnCount()):
            self.gridLayoutSimilarPrice.setColumnStretch(column, 1)

