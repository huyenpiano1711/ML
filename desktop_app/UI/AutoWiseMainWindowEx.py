class CardClicks(QObject):
    """Event filter on the car cards of Screen 3: a left click on a card opens its details window."""
    def __init__(self, parent, cards, onClick):
        super().__init__(parent)
        self.frames = {card.frame: card for card in cards}
        self.onClick = onClick
        for frame in self.frames:
            frame.setCursor(Qt.CursorShape.PointingHandCursor)
            frame.setToolTip("Click to see all details of this car")
            frame.installEventFilter(self)

    def eventFilter(self, obj, event):
        if (event.type() == QEvent.Type.MouseButtonRelease and obj in self.frames
                and event.button() == Qt.MouseButton.LeftButton):
            self.onClick(self.frames[obj])
            return True
        return False


