        ax1.scatter(y[idx], pred[idx], s=5, alpha=0.35, color=RED, edgecolors="none")
        lim = [0, float(np.percentile(y, 99))]
        ax1.plot(lim, lim, color=INK, linewidth=1)
        ax1.set_xlim(lim)
        ax1.set_ylim(lim)
        ChartUtil.money_axis(ax1.xaxis)
        ChartUtil.money_axis(ax1.yaxis)
        ax2 = ChartUtil.style(fig.add_subplot(122), "Average error by price level")
        bins = pd.cut(y, [0, 5000, 10000, 20000, 35000, 60000, 150001], labels=["<5k", "5-10k", "10-20k", "20-35k", "35-60k", ">60k"])
        mae = pd.Series(np.abs(y - pred)).groupby(bins, observed=True).mean()
        ax2.bar(mae.index.astype(str), mae.values, color=INK, width=0.6)
        ChartUtil.money_axis(ax2.yaxis)
        fig.tight_layout()
        canvas.draw()

