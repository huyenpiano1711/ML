def num(value, fmt="{:,.0f}", none="-"):
    try:
        if value is None or (isinstance(value, float) and np.isnan(value)):
            return none
        return fmt.format(value)
    except (TypeError, ValueError):
        return none


# ------------------------------------------------------------------------------------------ background jobs
class TrainWorker(QObject):
    """Trains one model in a QThread so the window stays responsive."""
    progress = pyqtSignal(str, int)
    finished = pyqtSignal(object)
    failed = pyqtSignal(str)
    splits = None                        # train/val/test loaded once per session

    def __init__(self, algorithm, params, log_target, augment):
        super().__init__()
        self.args = (algorithm, params, log_target, augment)

    def run(self):
        try:
            from src.prediction import model_trainer as mt
            if TrainWorker.splits is None:
                self.progress.emit("Loading train / validation data…", 10)
                TrainWorker.splits = mt.load_splits()
            steps = iter([35, 80, 95])
            result = mt.train_and_validate(*self.args, splits=TrainWorker.splits,
                                           progress=lambda msg: self.progress.emit(msg, next(steps, 95)))
            self.finished.emit(result)
        except Exception as exc:                                    # noqa: BLE001
            self.failed.emit(f"{type(exc).__name__}: {exc}")


