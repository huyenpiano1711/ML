    def busy(self, function, *args):
        """Run a slot with the wait cursor; any error goes to a dialog instead of closing the app."""
        QApplication.setOverrideCursor(Qt.CursorShape.WaitCursor)
        try:
            return function(*args)
        except Exception as exc:                                    # noqa: BLE001
            import traceback
            traceback.print_exc()
            QMessageBox.critical(self.MainWindow, "Something went wrong", f"{type(exc).__name__}: {exc}")
        finally:
            QApplication.restoreOverrideCursor()

