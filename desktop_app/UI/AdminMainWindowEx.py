    def showAlgorithmParams(self):
        key = self.comboBoxAlgorithm.currentData()
        spec = self.algorithms[key]
        names = list(spec["defaults"])
        for i, (label, box) in enumerate(self.paramWidgets):
            visible = i < len(names)
            label.setVisible(visible)
            box.setVisible(visible)
            if visible:
                name = names[i]
                lo, hi = spec["ranges"][name]
                label.setText(PARAM_LABELS.get(name, name.upper()))
                box.setProperty("param", name)
                is_int = isinstance(spec["defaults"][name], int)
                box.setDecimals(0 if is_int else 4)
                box.setRange(lo, hi)
                box.setSingleStep(1 if is_int else (0.01 if hi <= 1 else 0.1))
                box.setValue(spec["defaults"][name])
        self.checkBoxLogTarget.setEnabled(key != "dummy")

    def trainModel(self):
        if self.thread is not None:
            return
        key = self.comboBoxAlgorithm.currentData()
        params = {box.property("param"): box.value() for label, box in self.paramWidgets if box.isVisible()}
        self.pushButtonTrain.setEnabled(False)
        self.pushButtonSaveModel.setEnabled(False)
        self.progressBarTrain.show()
        self.progressBarTrain.setValue(3)
        self.labelTrainStatus.setText("Starting…")
        self.thread = QThread()
        self.worker = TrainWorker(key, params, self.checkBoxLogTarget.isChecked(), self.doubleSpinBoxAugment.value())
        self.worker.moveToThread(self.thread)
        self.thread.started.connect(self.worker.run)
        self.worker.progress.connect(self.trainProgress)
        self.worker.finished.connect(self.trainFinished)
        self.worker.failed.connect(self.trainFailed)
        self.worker.finished.connect(self.thread.quit)
        self.worker.failed.connect(self.thread.quit)
        self.thread.finished.connect(self.trainThreadDone)
        self.thread.start()

    def trainProgress(self, text, value):
        self.labelTrainStatus.setText(text)
        self.progressBarTrain.setValue(value)

    def trainThreadDone(self):
        self.thread.deleteLater()
        self.thread = None
        self.pushButtonTrain.setEnabled(True)

