    @staticmethod
    def readJson(path):
        try:
            return json.loads(Path(path).read_text(encoding="utf-8"))
        except Exception:                                           # noqa: BLE001
            return {}

    @staticmethod
    def lastDays(df, days=14, cols=("n",)):
        idx = pd.date_range(end=pd.Timestamp.today().normalize(), periods=days).strftime("%Y-%m-%d")
        if df is None or df.empty:
            return pd.DataFrame({c: 0 for c in cols}, index=idx)
        return df.set_index("day").reindex(idx).fillna(0)[list(cols)]

