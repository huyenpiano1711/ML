    def _runElbow(self):
        from sklearn.cluster import KMeans
        from sklearn.metrics import silhouette_score
        d, X, feats = self.segmentData()
        if d is None:
            return
        ks = list(range(2, self.spinBoxKMax.value() + 1))
        idx = np.random.default_rng(0).choice(len(X), size=min(3000, len(X)), replace=False)
        inertia, sil = [], []
        for k in ks:
            km = KMeans(n_clusters=k, init="k-means++", n_init=5, max_iter=300, random_state=42).fit(X)
            inertia.append(km.inertia_)
            sil.append(silhouette_score(X[idx], km.labels_[idx]))
        # elbow = point farthest from the line between the first and last point (Kneedle idea)
        x = (np.array(ks) - ks[0]) / (ks[-1] - ks[0])
        y = (np.array(inertia) - min(inertia)) / (max(inertia) - min(inertia) or 1)
        best = ks[int(np.argmax((1 - x) - y))]
        self.spinBoxK.setValue(best)
        fig, canvas = ChartUtil.canvas(self.verticalLayoutChartElbowPlot)
        ax = ChartUtil.style(fig.add_subplot(111))
        ax.plot(ks, inertia, color=INK, marker="o", markersize=4, label="inertia (WCSS)")
        ax.axvline(best, color=RED, linestyle="--", linewidth=1)
        ax2 = ax.twinx()
        ax2.plot(ks, sil, color=RED, marker="s", markersize=3, label="silhouette")
        ax2.tick_params(colors=MUTED, labelsize=8)
        ax2.spines["top"].set_visible(False)
        ax.set_xlabel("K", fontsize=8, color=MUTED)
        lines = ax.get_legend_handles_labels()[0] + ax2.get_legend_handles_labels()[0]
        ax.legend(lines, ["inertia (WCSS)", "silhouette"], frameon=False, fontsize=8)
        fig.tight_layout()
        canvas.draw()
        self.labelChartElbowNote.setText(f"Elbow at K = {best} (silhouette {sil[ks.index(best)]:.3f}). "
                                         f"Features: {', '.join(feats)}; {len(X):,} listings.")

    def runKMeans(self):
        self.busy(self._runKMeans)

    def _runKMeans(self):
        from sklearn.cluster import KMeans
        d, X, feats = self.segmentData()
        if d is None:
            return
        k = self.spinBoxK.value()
        km = KMeans(n_clusters=k, init="k-means++", n_init=10, max_iter=500, random_state=42).fit(X)
        d = d.assign(segment=km.labels_)
        prof = d.groupby("segment").agg(n=("price", "size"), price=("price", "median"), age=("car_age", "median"),
                                        odo=("odometer", "median")).sort_values("price")
        order = {seg: i + 1 for i, seg in enumerate(prof.index)}            # segment 1 = cheapest
        d["segment"] = d["segment"].map(order)
        prof.index = [order[s] for s in prof.index]
        names = self.segmentNames(prof)
        rows = []
        for seg, r in prof.iterrows():
            top = d[d["segment"] == seg]["manufacturer"].value_counts().head(3)
            rows.append([seg, f"{int(r['n']):,}", f"{r['n'] / len(d) * 100:.1f}%", money(r["price"]), f"{r['age']:.0f} yrs",
                         f"{r['odo']:,.0f} mi", ", ".join(makeLabel(m) for m in top.index), names[seg]])
        TableUtil.fill(self.tableWidgetClusters, rows, align_right=(1, 2, 3, 4, 5), stretch_col=6)
        fig, canvas = ChartUtil.canvas(self.verticalLayoutChartClustersPlot)
        ax = ChartUtil.style(fig.add_subplot(111))
        s = d.sample(min(4000, len(d)), random_state=3)
        xcol = "car_age" if "car_age" in feats else feats[0]
        ycol = "price" if "price" in feats else feats[1]
        for seg in sorted(s["segment"].unique()):
            part = s[s["segment"] == seg]
            ax.scatter(part[xcol], part[ycol], s=6, alpha=0.5, color=PALETTE[(seg - 1) % len(PALETTE)], edgecolors="none",
                       label=f"{seg}. {names[seg]}")
        ax.set_xlabel(xcol, fontsize=8, color=MUTED)
        ax.set_ylabel(ycol, fontsize=8, color=MUTED)
        if ycol == "price":
            ChartUtil.money_axis(ax.yaxis)
        ax.legend(frameon=False, fontsize=7, markerscale=2)
        fig.tight_layout()
        canvas.draw()
        self.plainTextEditClusterComment.setPlainText(self.segmentComment(prof, names, len(d), feats))
        AuditDao.log(self.user, "run_kmeans", f"K={k}", ",".join(feats))

    @staticmethod
    def segmentNames(prof):
        """Business names from the median price / age / mileage of each segment."""
        names = {}
        p_lo, p_hi = prof["price"].quantile([0.34, 0.67])
        for seg, r in prof.iterrows():
            tier = "Budget" if r["price"] <= p_lo else ("Premium" if r["price"] > p_hi else "Mid-range")
            age = "nearly new" if r["age"] <= 4 else ("older" if r["age"] >= 12 else "used")
            miles = ", high mileage" if r["odo"] >= 150000 else (", low mileage" if r["odo"] <= 50000 else "")
            names[seg] = f"{tier} {age}{miles}"
        return names

    @staticmethod
    def segmentComment(prof, names, n, feats):
        lines = [f"K-Means grouped {n:,} listings into {len(prof)} segments using {', '.join(feats)} (Min-Max scaled).", ""]
        for seg, r in prof.iterrows():
            lines.append(f"Segment {seg} - {names[seg]}: {r['n'] / n * 100:.0f}% of listings, median {money(r['price'])}, "
                         f"{r['age']:.0f} years old, {r['odo']:,.0f} miles.")
        cheap, rich = prof.iloc[0], prof.iloc[-1]
        lines += ["", f"Use: the cheapest segment ({money(cheap['price'])}) suits first-time buyers with a small budget; the most "
                      f"expensive one ({money(rich['price'])}) is where dealers should focus premium stock and financing offers. "
                      "Segments can also check that the recommender offers cars from the user's own segment."]
        return "\n".join(lines)

