    def loadUsers(self):
        role = {1: ROLE_USER, 2: ROLE_ADMIN}.get(self.comboBoxUserRole.currentIndex(), "")
        status = {1: "active", 2: "banned", 3: "locked"}.get(self.comboBoxUserStatus.currentIndex(), "")
        df = UserDao.listUsers(self.lineEditUserSearch.text(), role, status)
        from desktop_app.dal.user_dao import now
        current = now()
        rows = []
        for r in (df.itertuples() if df is not None else []):
            state = "Banned" if r.is_banned else ("Locked" if r.locked_until and r.locked_until > current else "Active")
            rows.append([r.id, r.username, r.full_name, r.email or "", r.role.title(), state, r.created_at,
                         r.last_login_at or "", r.n_searches])
        TableUtil.fill(self.tableWidgetUsers, rows, align_right=(0, 8), stretch_col=2)
        for i, row in enumerate(rows):
            color = {"Banned": "#B91C1C", "Locked": "#B45309"}.get(row[5])
            if color:
                TableUtil.colorCell(self.tableWidgetUsers, i, 5, fg=color, bold=True)
            if row[4] == "Admin":
                TableUtil.colorCell(self.tableWidgetUsers, i, 4, fg=RED, bold=True)
        self.labelUsersCount.setText(f"{len(rows)} account{'s' if len(rows) != 1 else ''}")

