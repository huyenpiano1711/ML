"""
PdfUtil.py - Export one analysis (form + price + Top 5 + same price range) as a PDF file.
Uses only Qt (QTextDocument + QPdfWriter), so nothing else has to be installed.
"""
import html
from datetime import datetime

from PyQt6.QtCore import QMarginsF, QSizeF
from PyQt6.QtGui import QPageLayout, QPageSize, QPdfWriter, QTextDocument

from desktop_app.widgets.vehicle_card import labelOf, makeLabel, modelLabel, money

RED, INK, MUTED = "#D7263D", "#18181B", "#6B6B74"


def esc(value):
    return html.escape("" if value is None else str(value))


def carTitle(car):
    return f"{makeLabel(car.get('manufacturer'))} {modelLabel(car.get('model_base'))} {car.get('year')}"


def carRows(cars, with_score):
    rows = []
    for n, car in enumerate(cars, 1):
        score = f"{car['score'] * 100:.0f}%" if with_score and car.get("score") is not None else ""
        rows.append(f"<tr><td>{n}</td><td><b>{esc(carTitle(car))}</b></td><td align='right'>{esc(money(car['price']))}</td>"
                    f"<td align='right'>{car['odometer']:,.0f} mi</td><td>{esc(labelOf('condition', car.get('condition')))}</td>"
                    f"<td>{esc(labelOf('fuel', car.get('fuel')))} · {esc(labelOf('transmission', car.get('transmission')))}</td>"
                    f"<td>{esc((car.get('state') or '').upper())}</td><td align='right'>{score}</td></tr>")
    return "".join(rows)


def analysisHtml(user_name, vehicle, payload, created_at=None):
    """vehicle: dict of VehicleInput; payload: dict saved by SearchDao.save (price, top_matches, similar_price)."""
    price = payload.get("price") or {}
    title = f"{makeLabel(vehicle['manufacturer'])} {modelLabel(vehicle['model_base'])} {vehicle['year']}"
    details = [f"{float(vehicle['odometer']):,.0f} mi"] + [labelOf(f, vehicle.get(f)) for f in ("type", "condition", "fuel", "transmission")
                                                          if vehicle.get(f)]
    budget = float(vehicle["budget_max_usd"])
    verdict = ""
    if price.get("predicted_price"):
        gap = price["predicted_price"] - budget
        verdict = (f"<span style='color:#B91C1C'><b>Over budget by {money(gap)}</b></span>" if gap > 0
                   else f"<span style='color:#15803D'><b>Within budget ({money(-gap)} to spare)</b></span>")
    rng = (f"8 in 10 similar listings: {money(price['price_low'])} – {money(price['price_high'])}"
           if price.get("price_low") is not None else "")
    style = (f"body{{font-family:'Inter','Segoe UI',Arial;color:{INK};font-size:10pt}} h1{{font-family:'Playfair Display',Georgia;"
             f"font-size:22pt;margin:0}} h2{{font-family:'Playfair Display',Georgia;font-size:14pt;margin:14px 0 4px 0}}"
             f".eyebrow{{color:{RED};font-size:8pt;font-weight:bold;letter-spacing:2px}} .muted{{color:{MUTED}}}"
             f"table{{border-collapse:collapse;width:100%}} th{{background:#FAFAFB;color:{MUTED};font-size:8pt;text-align:left;"
             f"padding:5px;border-bottom:1px solid #E4E4E9}} td{{padding:5px;border-bottom:1px solid #F0F0F2}}")
    return f"""<html><head><style>{style}</style></head><body>
<p class='eyebrow'>AUTOWISE · AI CAR ADVISOR</p>
<h1>Analysis for {esc(user_name)}</h1>
<p class='muted'>{esc(created_at or datetime.now().strftime('%Y-%m-%d %H:%M'))}</p>
<h2>{esc(title)}</h2><p>{esc(' · '.join(details))}</p>
<table width='100%' cellspacing='0'><tr><th>ESTIMATED ASKING PRICE</th><th>YOUR BUDGET</th></tr>
<tr><td><span style='font-size:20pt;font-family:Georgia'>{esc(money(price['predicted_price'])) if price.get('predicted_price') else 'N/A'}</span><br>
<span class='muted'>{esc(rng)}</span></td>
<td><span style='font-size:20pt;font-family:Georgia'>{esc(money(budget))}</span><br>{verdict}</td></tr></table>
<p class='muted'>Estimate learned from U.S. used-car listings of 2021 (Craigslist), not today's market price.
Model: {esc(price.get('model_name', ''))}.</p>
<h2>Top {len(payload.get('top_matches', []))} matches within your budget</h2>
<table width='100%' cellspacing='0'><tr><th>#</th><th>CAR</th><th>PRICE</th><th>MILEAGE</th><th>CONDITION</th><th>FUEL · GEARBOX</th><th>STATE</th><th>MATCH</th></tr>
{carRows(payload.get('top_matches', []), True)}</table>
<h2>Other cars in the same price range</h2>
<table width='100%' cellspacing='0'><tr><th>#</th><th>CAR</th><th>PRICE</th><th>MILEAGE</th><th>CONDITION</th><th>FUEL · GEARBOX</th><th>STATE</th><th></th></tr>
{carRows(payload.get('similar_price', []), False)}</table>
<p class='muted' style='margin-top:18px'>Generated by AutoWise AI · Machine Learning in Business Analytics course project (UEL).</p>
</body></html>"""


def saveHtmlAsPdf(html_text, path):
    writer = QPdfWriter(str(path))
    writer.setPageLayout(QPageLayout(QPageSize(QPageSize.PageSizeId.A4), QPageLayout.Orientation.Portrait,
                                     QMarginsF(15, 15, 15, 15), QPageLayout.Unit.Millimeter))
    writer.setResolution(110)
    doc = QTextDocument()
    doc.setHtml(html_text)
    doc.setPageSize(QSizeF(writer.width(), writer.height()))
    doc.print(writer)
    return path
